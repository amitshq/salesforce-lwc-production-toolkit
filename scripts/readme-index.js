/* eslint-env node */
/**
 * Builds the "What's inside" list in README.md from docs/goals.js and docs/catalog.js, so the README and the
 * website cannot drift apart. The list lives between two marker comments in the README.
 *
 *   npm run docs:readme    rewrites that block in README.md
 *   npm run test:site      fails if README.md is out of date
 */
const fs = require('node:fs');
const path = require('node:path');
const catalog = require('../docs/catalog.js');
const goals = require('../docs/goals.js');

const START = '<!-- inside:start - generated by "npm run docs:readme" from docs/goals.js and docs/catalog.js; do not edit by hand -->';
const END = '<!-- inside:end -->';
const README = path.join(__dirname, '..', 'README.md');

function bullet(item) {
  return `- [\`${item.name}\`](force-app/main/default/${item.path}) - ${item.tagline}`;
}

/** The generated block, markers included. */
function render() {
  const byId = new Map(catalog.map((item) => [item.id, item]));
  const sections = goals.map((goal) => {
    const items = goal.ids.map((id) => byId.get(id));
    const count = items.length === 1 ? '1 piece' : `${items.length} pieces`;
    return [`<details>`, `<summary><b>${goal.label}</b> &middot; ${count}</summary>`, '', goal.blurb, '', ...items.map(bullet), '', `</details>`].join('\n');
  });
  return [START, '', sections.join('\n\n'), '', END].join('\n');
}

/** Returns the README text with the generated block replaced; throws if the markers are missing. */
function apply(text) {
  const normalized = text.replace(/\r\n/g, '\n');
  const start = normalized.indexOf('<!-- inside:start');
  const end = normalized.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error('README.md needs the <!-- inside:start --> and <!-- inside:end --> markers.');
  }
  return normalized.slice(0, start) + render() + normalized.slice(end + END.length);
}

if (require.main === module) {
  const current = fs.readFileSync(README, 'utf8');
  const usesCrlf = current.includes('\r\n');
  let updated = apply(current);
  if (usesCrlf) {
    updated = updated.replace(/\n/g, '\r\n');
  }
  fs.writeFileSync(README, updated);
  process.stdout.write('README.md updated\n');
}

module.exports = { render, apply, START, END };
